def build_ranking() -> list[dict]:
    rows = []
    for d in DATASETS:
        s = SCORES.get(d["id"], (0,) * 7)
        row = {"id": d["id"], "name": d["name"], "category": d["category"]}
        row.update(dict(zip(CRITERIA, s)))
        row["excluded"] = sum(s) == 0
        rows.append(row)
    # sort lexicographically by the criteria in priority order (statistical power first),
    # excluded (blocked/account-gated) sources sink to the bottom regardless of score
    rows.sort(key=lambda r: (r["excluded"], tuple(-r[c] for c in CRITERIA)))
    for i, r in enumerate(rows, 1):
        r["rank"] = i
    return rows


def main() -> None:
    (OUT / "datasets.json").write_text(json.dumps(DATASETS, indent=2))
    ranking = build_ranking()
    with (OUT / "ranking.csv").open("w", newline="") as f:
        fieldnames = ["rank", "id", "name", "category"] + CRITERIA + ["excluded"]
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in ranking:
            w.writerow(r)
    print(f"wrote {OUT/'datasets.json'} ({len(DATASETS)} datasets)")
    print(f"wrote {OUT/'ranking.csv'} ({len(ranking)} rows)")


if __name__ == "__main__":
    main()
