"""Validation of single-series constructions vs ETFs / published references (no sleeve mixes).

Writes data/cycle8/notes/bond_checks.md and data/cycle8/notes/gold_checks.md.
Usage: python research/cycle8/data_rates/validate.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bondmath as bm  # noqa: E402
from build import LAST_FULL_MONTH, RAW, month_end_last, yahoo  # noqa: E402

ROOT = HERE.parents[2]
PROC = ROOT / "data" / "cycle8" / "proc"
NOTES = ROOT / "data" / "cycle8" / "notes"


def etf_monthly(sym: str) -> pd.Series:
    px = month_end_last(yahoo(sym)["adjclose"])
    return px.pct_change().dropna().rename(sym)


def etf_daily(sym: str) -> pd.Series:
    return yahoo(sym)["adjclose"].pct_change().dropna().rename(sym)


def cagr(r: pd.Series, per: int) -> float:
    return float((1 + r).prod() ** (per / len(r)) - 1)


def compare(sim: pd.Series, ref: pd.Series, per: int = 12, start: str | None = None) -> dict:
    j = pd.concat([sim, ref], axis=1, keys=["sim", "ref"]).dropna()
    if start:
        j = j.loc[start:]
    d = j["sim"] - j["ref"]
    beta = float(np.cov(j["ref"], j["sim"])[0, 1] / j["sim"].var())  # ref on sim
    return {"first": j.index.min().strftime("%Y-%m"), "last": j.index.max().strftime("%Y-%m"), "n": len(j),
            "corr": j.corr().iloc[0, 1], "cagr_sim": cagr(j["sim"], per), "cagr_ref": cagr(j["ref"], per),
            "gap_cagr": cagr(j["sim"], per) - cagr(j["ref"], per), "gap_arith": d.mean() * per,
            "te": d.std() * np.sqrt(per), "vol_sim": j["sim"].std() * np.sqrt(per),
            "vol_ref": j["ref"].std() * np.sqrt(per), "beta_ref_on_sim": beta}


def cal_year(r: pd.Series, y: int) -> float:
    s = r[r.index.year == y].dropna()
    return float((1 + s).prod() - 1) if len(s) else float("nan")


def fmt_row(name: str, c: dict) -> str:
    return (f"| {name} | {c['first']}..{c['last']} | {c['n']} | {c['corr']:.3f} | {c['cagr_sim']:.2%} | "
            f"{c['cagr_ref']:.2%} | {c['gap_cagr']:+.2%} | {c['gap_arith']:+.2%} | {c['te']:.2%} | "
            f"{c['vol_sim']:.2%} | {c['vol_ref']:.2%} | {c['beta_ref_on_sim']:.2f} |")


HDR = ("| sim vs ref | overlap | n | corr | CAGR sim | CAGR ref | gap CAGR (sim−ref) | gap arith/yr | TE/yr | "
       "vol sim | vol ref | β ref on sim |\n|---|---|---|---|---|---|---|---|---|---|---|---|")


def damodaran() -> pd.Series:
    t = pd.read_excel(RAW / "damodaran_histretSP.xls", sheet_name="T. Bond yield & return", header=None)
    t = t.iloc[7:, :3].dropna(subset=[0])
    t = t[pd.to_numeric(t[0], errors="coerce").notna()]
    s = pd.Series(pd.to_numeric(t[2], errors="coerce").to_numpy(), index=t[0].astype(int)).dropna()
    return s


def main() -> None:
    NOTES.mkdir(parents=True, exist_ok=True)
    bmo = pd.read_parquet(PROC / "bond_monthly.parquet")
    bd = pd.read_parquet(PROC / "bond_daily.parquet")
    L = ["# Cycle 8 bond construction checks (single series only)", "",
         "Generated by `research/cycle8/data_rates/validate.py`. Simulated series: par-bond repricing (FRAMEWORK §2), "
         "no fees. ETF returns: Yahoo adjclose, month-end (local currency). Gap = simulated − ETF; ETFs are net of "
         "their MER (IEF 0.15%, TLT 0.15%, XBB 0.10%, ZAG 0.09%, VAB 0.09%, VFITX 0.10%, VUSTX 0.10%). "
         "β = regression of ETF on the simulated series (≈ duration ratio ETF/10Y CMT).", ""]
    ms = {s: etf_monthly(s) for s in ("IEF", "TLT", "XBB.TO", "ZAG.TO", "VAB.TO", "VFITX", "VUSTX")}

    L += ["## Monthly: US10_ret (USD)", "", HDR]
    for s in ("IEF", "VFITX"):
        L.append(fmt_row(f"US10 vs {s}", compare(bmo["US10_ret"], ms[s])))
    L += ["", "IEF holds 7–10y Treasuries (duration ≈ 7–7.5y) vs the 10Y par bond (≈ 8y at 4–5%): expect β < 1 "
          "and IEF CAGR slightly below in rising-rate spans. VFITX (intermediate Treasury fund, duration ≈ 5–6y) is "
          "a longer pre-ETF reference (1991+).", ""]

    # Damodaran annual
    dm = damodaran()
    ann = (1 + bmo["US10_ret"]).groupby(bmo.index.year).prod() - 1
    j = pd.concat([ann, dm], axis=1, keys=["sim", "dam"]).dropna().loc[1928:LAST_FULL_MONTH.year - 1]
    dd = j["sim"] - j["dam"]
    L += ["## Annual: US10_ret vs Damodaran 'T.Bond' return (free long reference)", "",
          "Damodaran reprices a 10Y par bond ONCE a year on year-end yields (Shiller/FRED); ours compounds 12 "
          "monthly repricings, so the two differ by roll-down/reinvestment and by the pre-1953 interpolated yields.",
          "", "| span | years | corr | mean sim | mean Damodaran | mean gap | sd gap | max abs gap (year) |",
          "|---|---|---|---|---|---|---|---|"]
    for a, b in ((1928, 1952), (1953, 1961), (1962, 2025), (1928, 2025)):
        x = j.loc[a:b]
        g = dd.loc[a:b]
        L.append(f"| {a}–{b} | {len(x)} | {x.corr().iloc[0, 1]:.3f} | {x['sim'].mean():.2%} | {x['dam'].mean():.2%} | "
                 f"{g.mean():+.2%} | {g.std():.2%} | {g.abs().max():.2%} ({int(g.abs().idxmax())}) |")
    L.append("")

    L += ["## Monthly: CA10_ret (CAD)", "", HDR]
    for s in ("XBB.TO", "ZAG.TO", "VAB.TO"):
        L.append(fmt_row(f"CA10 vs {s}", compare(bmo["CA10_ret"], ms[s])))
    L += ["", "XBB/ZAG/VAB track the FTSE Canada Universe / Bloomberg Canada Aggregate: ≈ 7–7.5y duration, ~35% "
          "provincial + ~10–15% corporate (credit spread carry, spread moves), vs a pure 10Y GoC par bond (≈ 8y). "
          "Expect β < 1, correlation < 1 and a positive ETF carry advantage from spread in calm years.", ""]

    # 2022 and other calendar years
    L += ["## Calendar-year returns side by side", "",
          "| year | US10 sim | IEF | VFITX | CA10 sim | XBB | ZAG | VAB |", "|---|---|---|---|---|---|---|---|"]
    for y in (2008, 2013, 2018, 2020, 2021, 2022, 2023, 2024, 2025):
        L.append(f"| {y} | {cal_year(bmo['US10_ret'], y):.2%} | {cal_year(ms['IEF'], y):.2%} | "
                 f"{cal_year(ms['VFITX'], y):.2%} | {cal_year(bmo['CA10_ret'], y):.2%} | "
                 f"{cal_year(ms['XBB.TO'], y):.2%} | {cal_year(ms['ZAG.TO'], y):.2%} | {cal_year(ms['VAB.TO'], y):.2%} |")
    L.append("")

    # Daily
    L += ["## Daily", "",
          "Daily par-bond returns (step 1/252) vs ETF adjclose daily returns. Note FRED CMT yields are ~3:30pm ET "
          "bid-side indications; ETF closes are 4pm — daily correlation is capped by that timing noise.", "",
          HDR.replace("TE/yr", "TE/yr (√252)")]
    ds = {s: etf_daily(s) for s in ("TLT", "IEF", "VUSTX", "XBB.TO")}
    daily_pairs = (("US20", "TLT"), ("US20", "VUSTX"), ("US10", "IEF"), ("CA10", "XBB.TO"))
    for a, s in daily_pairs:
        L.append(fmt_row(f"{a} daily vs {s}", compare(bd[f"{a}_ret"], ds[s], per=252)))
    L += ["", "TLT holds 20y+ Treasuries (duration ≈ 16–17y) vs the 20Y CMT par bond (≈ 13–14y): β ≈ 1.2 expected. "
          "VUSTX = Vanguard Long-Term Treasury fund (1986+, duration ≈ 15–16y).", ""]
    # Monthly-compounded check of the daily series + annual US20 vs TLT
    L += ["### US20 daily vs TLT, calendar years", "", "| year | US20 sim | TLT | diff |", "|---|---|---|---|"]
    us20 = bd["US20_ret"].dropna()
    tlt = ds["TLT"]
    for y in range(2003, LAST_FULL_MONTH.year + 1):
        a_, b_ = cal_year(us20, y), cal_year(tlt, y)
        tag = " (YTD)" if y == LAST_FULL_MONTH.year else ""
        L.append(f"| {y}{tag} | {a_:.2%} | {b_:.2%} | {a_ - b_:+.2%} |")
    # consistency: daily-compounded monthly vs monthly par-bond
    L += ["", "### Consistency: daily-compounded vs monthly par-bond returns (same yields source family)", "",
          "| series | months | corr | CAGR daily-compounded | CAGR monthly | gap |", "|---|---|---|---|---|---|"]
    for a in ("US10", "CA10"):
        dm_ = (1 + bd[f"{a}_ret"].dropna()).resample("ME").prod() - 1
        c = compare(dm_.loc[:LAST_FULL_MONTH], bmo[f"{a}_ret"],
                    start="1962-02" if a == "US10" else "2001-02")
        L.append(f"| {a} | {c['n']} | {c['corr']:.4f} | {c['cagr_sim']:.2%} | {c['cagr_ref']:.2%} | "
                 f"{c['gap_cagr']:+.2%} |")
    L += ["", "Daily compounding adds convexity/roll-down relative to monthly repricing; small positive gap expected.",
          ""]
    L += ["## Unit tests", "", "`tests/test_cycle8_bond.py`: par price = 1 at coupon yield; zero yield change → "
          "return = y·Δ exactly; +100bp on a 5% 10Y → ≈ −7.0% (modified duration 7.79 minus convexity plus carry).",
          ""]
    (NOTES / "bond_checks.md").write_text("\n".join(L))
    print("\n".join(L))

    # ---------------------------------------------------------------- gold
    gm = pd.read_parquet(PROC / "gold_monthly.parquet")
    gd = pd.read_parquet(PROC / "gold_daily.parquet")
    wb = gm["gold_usd_wb_avg"].pct_change()
    gcf = gm["gold_usd_gcf_me"].pct_change()
    gld = gm["gld_adjclose_me"].pct_change()
    G = ["# Cycle 8 gold checks", "", "Generated by `research/cycle8/data_rates/validate.py`. GLD expense ratio "
         "0.40%/yr since inception (2004-11); a spot series "
         "should beat GLD by ≈ 0.40%/yr. GC=F is the front-month COMEX future (carries the futures basis ≈ cash "
         "rate minus lease rate, so its return vs spot differs by the roll yield — at month-end the continuous "
         "series also splices contracts without back-adjustment).", "", HDR]
    G.append(fmt_row("GC=F month-end vs GLD", compare(gcf, gld)))
    G.append(fmt_row("WB monthly avg vs GLD (month-end)", compare(wb, gld)))
    G.append(fmt_row("WB monthly avg vs GC=F month-end", compare(wb, gcf)))
    # average-of-GLD vs WB avg (like-for-like timing)
    gld_avg = gd["gld_adjclose"].resample("ME").mean().loc[:LAST_FULL_MONTH].pct_change()
    G.append(fmt_row("WB monthly avg vs GLD monthly-AVERAGE", compare(wb, gld_avg)))
    gdr = gd["gold_usd_gcf"].pct_change()
    G.append(fmt_row("GC=F daily vs GLD daily", compare(gdr, gd["gld_adjclose"].pct_change(), per=252)))
    ac_wb = wb.loc["1971":].autocorr()
    ac_gcf = gcf.dropna().autocorr()
    G += ["", f"Lag-1 autocorrelation of monthly returns: WB average series 1971+ = {ac_wb:.2f}; GC=F month-end "
          f"= {ac_gcf:.2f}. The World Bank series is a monthly AVERAGE (datapackage.json and World Bank Pink Sheet "
          "definition), so its returns are smoothed and lagged by ~half a month; like-for-like timing (GLD monthly "
          "average) restores the correlation. Use it for long history with that caveat, or the month-end series "
          "where available (2000-08+).", "",
          "| year | WB avg (Dec/Dec avg) | GC=F | GLD |", "|---|---|---|---|"]
    for y in (2008, 2011, 2013, 2020, 2022, 2023, 2024, 2025):
        G.append(f"| {y} | {cal_year(wb, y):.2%} | {cal_year(gcf, y):.2%} | {cal_year(gld, y):.2%} |")
    (NOTES / "gold_checks.md").write_text("\n".join(G) + "\n")
    print("\n".join(G))


if __name__ == "__main__":
    main()
