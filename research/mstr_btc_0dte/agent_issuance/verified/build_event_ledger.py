def main() -> None:
    scanned = pd.read_csv(HERE / "source_scan.csv")
    event_frame = pd.DataFrame(EVENTS)
    ledger = event_frame.merge(
        scanned[
            [
                "accession",
                "filing_date",
                "acceptance_utc",
                "form",
                "items",
                "primary_document",
                "source_url",
                "source_sha256",
                "local_cache",
            ]
        ],
        on="accession",
        how="left",
        validate="one_to_one",
    )
    if ledger.source_url.isna().any():
        missing = ledger.loc[ledger.source_url.isna(), "accession"].tolist()
        raise RuntimeError(f"chosen source missing from verified scan: {missing}")
    acceptance = pd.to_datetime(ledger.acceptance_utc, utc=True).dt.tz_convert("America/New_York")
    ledger["acceptance_et"] = acceptance.astype(str)
    ledger["acceptance_et_clock"] = acceptance.dt.strftime("%Y-%m-%d %H:%M:%S %Z")
    ledger["source_method"] = "SEC EDGAR primary document; acceptanceDateTime from submissions metadata"
    ledger["included"] = True
    order = [
        "event_id", "family", "sample", "filing_date", "acceptance_utc", "acceptance_et_clock",
        "accession", "form", "items", "announced_amount_usd", "description", "primary_document",
        "source_url", "source_sha256", "local_cache", "source_method", "included",
    ]
    ledger = ledger[order].sort_values("acceptance_utc")
    ledger.to_csv(HERE / "event_ledger.csv", index=False)

    exclusions = pd.DataFrame(
        [
            ["convertible completion / pricing follow-on", "later completion 8-Ks", "same offering already represented by earliest SEC announcement"],
            ["weekly ATM-sale and BTC-update 8-Ks", "recurring reports", "would duplicate the separate BTC-purchase-event research and are not new programs"],
            ["June 2021 senior secured notes", "8-K 0001193125-21-189600", "not a convertible offering"],
            ["2025+ STRK/STRF/STRD/STRC preferred ATM programs", "preferred-stock filings", "no comparable development family; excluded before returns"],
            ["shelf registration without a named sales agreement", "generic registration filing", "capacity alone is not a discrete new common-ATM announcement"],
            ["omnibus consolidation of existing programs", "2025-11-04 Common Stock Annex carried over the remaining $15,854,365,265 of the May 2025 program", "re-papering of existing programs without new capacity; not a new program"],
            ["administrative amendments and sales-agent joinders", "Amendments No. 1-2 to the Omnibus Sales Agreement; March 2026 agent joinders", "no new capacity; a capacity-adding program addendum is retained as its own event"],
            ["underwritten preferred stock IPOs", "STRE perpetual stream preferred IPO, November 2025", "underwritten offering priced through a term sheet; not an ATM program and outside the common-stock family"],
        ],
        columns=["exclusion_class", "examples", "reason"],
    )
    exclusions.to_csv(HERE / "event_exclusions.csv", index=False)
    print(ledger[["event_id", "family", "sample", "acceptance_et_clock", "announced_amount_usd"]].to_string(index=False))
    print(
        f"ledger events={len(ledger)}; "
        f"development={sum(ledger['sample'] == 'development_2020_2023')}; "
        f"holdout={sum(ledger['sample'] == 'holdout_2024_2026')}"
    )


if __name__ == "__main__":
    main()
